#!/usr/bin/env python3
"""Generate large benchmark netlists: an N x N on-chip power grid (IR-drop) or RC mesh.

  python3 tools/gen_grid.py 100 > grid100.cir              # DC IR-drop analysis, 10,000 nodes
  python3 tools/gen_grid.py 100 --rc > mesh100.cir         # transient RC mesh with switching loads
"""
import argparse

ap = argparse.ArgumentParser()
ap.add_argument("n", type=int, help="grid is n x n nodes")
ap.add_argument("--rc", action="store_true", help="add node capacitance and switching loads, run .tran")
ap.add_argument("--r", default="0.5", help="segment resistance (ohms)")
ap.add_argument("--load", default="50u", help="DC load current per node (amps)")
a = ap.parse_args()
n = a.n

node = lambda i, j: f"n{i}_{j}"
print(f"* {n}x{n} {'RC mesh' if a.rc else 'power grid'} ({n*n} nodes), generated by tools/gen_grid.py")
print("VDD vdd 0 DC 1.0")
for k, (i, j) in enumerate([(0, 0), (0, n - 1), (n - 1, 0), (n - 1, n - 1)]):
    print(f"RPAD{k} vdd {node(i, j)} 0.05")
for i in range(n):
    for j in range(n):
        if j + 1 < n: print(f"RH{i}_{j} {node(i,j)} {node(i,j+1)} {a.r}")
        if i + 1 < n: print(f"RV{i}_{j} {node(i,j)} {node(i+1,j)} {a.r}")
        if a.rc:
            print(f"C{i}_{j} {node(i,j)} 0 10f")
            # loads switch with a pseudo-random phase so the supply sees a ripple
            td = ((i * 7 + j * 13) % 10) * 20
            print(f"I{i}_{j} {node(i,j)} 0 PULSE(0 {a.load} {td}p 50p 50p 400p 1n)")
        else:
            print(f"I{i}_{j} {node(i,j)} 0 DC {a.load}")
c = n // 2
print(f".probe v({node(0,0)}) v({node(c,c)}) v({node(n-1,n//3)})")
print(".tran 20p 3n" if a.rc else ".op")
